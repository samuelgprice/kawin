def mole_fractions(w):
    """(x_Cr, x_Ni) from weight fractions of Cr and Ni (balance Fe)."""
    n = {"CR": w["CR"] / MOLAR_MASS["CR"], "NI": w["NI"] / MOLAR_MASS["NI"], "FE": (1.0 - w["CR"] - w["NI"]) / MOLAR_MASS["FE"]}
    total = sum(n.values())
    return np.array([n["CR"] / total, n["NI"] / total])

