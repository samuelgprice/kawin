        scale = {"A": 1.0, "B": 0.7, "C": 1.3}[phase]
        matrix = scale * np.asarray([[1.0, 0.1], [0.05, 0.8]], dtype=np.float64)
        if values.ndim == 2:
            return np.broadcast_to(matrix, (values.shape[0], 2, 2)).copy()
        return matrix

